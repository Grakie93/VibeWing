function format(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match,
  )
}

export function t(key: string, params?: Record<string, string | number>): string {
  const map = messages[language.value] || messages['en']
  const template = map[key] ?? messages['en'][key] ?? key
  return format(template, params)
}

export function locale(): Language {
  return language.value
}

export function setLanguage(value: Language) {
  language.value = value
}

/**
 * Reactive text bag. Components access `text.serviceStart`, `text.gitBranch`, etc.
 * and Vue auto-rerenders on language changes.
 */
export interface TextBag {
  [key: string]: string
}

function buildBag(lang: Language): TextBag {
  const map = messages[lang]
  const bag: TextBag = {}
  for (const key of Object.keys(map)) bag[key] = map[key]
  return bag
}

export const text = computed<TextBag>(() => buildBag(language.value))
